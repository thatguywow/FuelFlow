#!/usr/bin/env node
/**
 * Makes the Android system chrome match the app.
 *
 * Capacitor's generated theme leaves the navigation bar at the platform
 * default, which on most devices is a light grey strip with dark icons. Against
 * a dark app that strip is the brightest thing on screen and the first thing
 * the eye goes to — the app looks like a web page in a browser rather than a
 * native app.
 *
 * Three things are set here:
 *
 *   navigationBarColor / windowLightNavigationBar — the bar and its icons.
 *   statusBarColor / windowLightStatusBar         — the same at the top.
 *   windowBackground                              — what the OS paints while
 *     the activity starts, before the WebView has drawn anything. Left at the
 *     default it is a white or black flash on every cold launch.
 *
 * A `values-night` variant is written alongside the default so the chrome
 * follows the system theme, which is what the app's own "system" setting does.
 *
 * The `android/` directory is generated by `cap add android` in CI rather than
 * committed, so this runs after generation. It is idempotent.
 *
 * Usage: node scripts/patch-android-theme.mjs [android/app/src/main/res]
 */

import { readFileSync, writeFileSync, existsSync, mkdirSync } from 'node:fs';
import path from 'node:path';

const RES = process.argv[2] ?? 'android/app/src/main/res';

// Straight from the web theme's tokens, so the seam between the OS chrome and
// the app is invisible.
const DARK_BG = '#080A0F';
const LIGHT_BG = '#F5F7FB';

if (!existsSync(RES)) {
  console.error(`No res directory at ${RES}. Run \`npx cap add android\` first.`);
  process.exit(1);
}

/** Adds or replaces a <color> entry. */
function upsertColor(xml, name, value) {
  const existing = new RegExp(`<color name="${name}">[^<]*</color>`);
  if (existing.test(xml)) return xml.replace(existing, `<color name="${name}">${value}</color>`);
  return xml.replace('</resources>', `    <color name="${name}">${value}</color>\n</resources>`);
}

/** Adds or replaces an <item> inside a named <style>. */
function upsertStyleItem(xml, styleName, itemName, value) {
  const styleRe = new RegExp(`(<style name="${styleName}"[^>]*>)([\\s\\S]*?)(</style>)`);
  const match = styleRe.exec(xml);
  if (!match) return xml;
  let body = match[2];
  const itemRe = new RegExp(`<item name="${itemName}">[^<]*</item>`);
  body = itemRe.test(body)
    ? body.replace(itemRe, `<item name="${itemName}">${value}</item>`)
    : `${body.replace(/\s*$/, '')}\n        <item name="${itemName}">${value}</item>\n    `;
  return xml.replace(styleRe, `$1${body}$3`);
}

// --- colours --------------------------------------------------------------
const colorsPath = path.join(RES, 'values', 'colors.xml');
let colors = existsSync(colorsPath)
  ? readFileSync(colorsPath, 'utf8')
  : '<?xml version="1.0" encoding="utf-8"?>\n<resources>\n</resources>\n';
colors = upsertColor(colors, 'ffSystemChrome', DARK_BG);
writeFileSync(colorsPath, colors);

const nightColorsDir = path.join(RES, 'values-night');
mkdirSync(nightColorsDir, { recursive: true });
writeFileSync(
  path.join(nightColorsDir, 'colors.xml'),
  `<?xml version="1.0" encoding="utf-8"?>\n<resources>\n    <color name="ffSystemChrome">${DARK_BG}</color>\n</resources>\n`,
);

// The default (light) qualifier gets the light ground, so a device in light
// mode does not show a dark bar under a light app.
const lightColorsPath = path.join(RES, 'values', 'colors.xml');
writeFileSync(lightColorsPath, upsertColor(readFileSync(lightColorsPath, 'utf8'), 'ffSystemChrome', LIGHT_BG));

// --- styles ---------------------------------------------------------------
const stylesPath = path.join(RES, 'values', 'styles.xml');
if (!existsSync(stylesPath)) {
  console.error(`No styles.xml at ${stylesPath}.`);
  process.exit(1);
}

let styles = readFileSync(stylesPath, 'utf8');
const CHROME = '@color/ffSystemChrome';

for (const style of ['AppTheme.NoActionBar', 'AppTheme.NoActionBarLaunch']) {
  styles = upsertStyleItem(styles, style, 'android:navigationBarColor', CHROME);
  styles = upsertStyleItem(styles, style, 'android:statusBarColor', CHROME);
  // Light chrome in the default (light) configuration means dark icons.
  styles = upsertStyleItem(styles, style, 'android:windowLightNavigationBar', 'true');
  styles = upsertStyleItem(styles, style, 'android:windowLightStatusBar', 'true');
  styles = upsertStyleItem(styles, style, 'android:windowBackground', CHROME);
}
writeFileSync(stylesPath, styles);

// The night variant only has to flip the icon polarity; the colour resource
// already resolves to the dark ground under -night.
const nightStyles = `<?xml version="1.0" encoding="utf-8"?>
<resources>
    <!-- Written by scripts/patch-android-theme.mjs. Dark ground means light
         icons in both bars. -->
    <style name="AppTheme.NoActionBar" parent="Theme.AppCompat.DayNight.NoActionBar">
        <item name="windowActionBar">false</item>
        <item name="windowNoTitle">true</item>
        <item name="android:background">@null</item>
        <item name="android:navigationBarColor">@color/ffSystemChrome</item>
        <item name="android:statusBarColor">@color/ffSystemChrome</item>
        <item name="android:windowLightNavigationBar">false</item>
        <item name="android:windowLightStatusBar">false</item>
        <item name="android:windowBackground">@color/ffSystemChrome</item>
    </style>
</resources>
`;
mkdirSync(path.join(RES, 'values-night'), { recursive: true });
writeFileSync(path.join(RES, 'values-night', 'styles.xml'), nightStyles);

console.log('Patched Android system chrome:');
console.log(`  navigation + status bar -> @color/ffSystemChrome (${LIGHT_BG} / ${DARK_BG} at night)`);
console.log('  window background set, so a cold launch no longer flashes white');
